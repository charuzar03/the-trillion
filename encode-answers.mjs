// Scrambles answer-key.mjs into index.html so answers aren't readable in the page source.
// Run in this folder after editing answer-key.mjs:   node encode-answers.mjs
import fs from "fs";
import key from "./answer-key.mjs";

const K = Buffer.from("tricia-one-in-a-trillion");
function scramble(obj, n) { // must mirror unscramble() in index.html
  const b = Buffer.from(JSON.stringify(obj), "utf8");
  for (let i = 0; i < b.length; i++) b[i] ^= K[(i * 7 + n * 13) % K.length] ^ ((i * 131 + 17) & 255);
  return b.toString("base64");
}

const lines = key.map((q, n) => {
  const { prompt, ...secret } = q;
  return `    { prompt: ${JSON.stringify(prompt)},\n      secret: "${scramble(secret, n)}" },`;
});
const START = "  /* <questions> generated by encode-answers.mjs from answer-key.mjs: edit answers there, not here */";
const END = "  /* </questions> */";
const html = fs.readFileSync("index.html", "utf8");
const a = html.indexOf(START), b = html.indexOf(END);
if (a < 0 || b < 0) throw new Error("question markers not found in index.html");
fs.writeFileSync("index.html", html.slice(0, a) + START + "\n  questions: [\n" + lines.join("\n") + "\n  ],\n" + html.slice(b));
console.log(`encoded ${key.length} questions into index.html`);
